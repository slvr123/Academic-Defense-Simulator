// npm run gen:api [source]
// Writes two files from the backend's OpenAPI schema:
//   src/api/schema.gen.ts  - the types (openapi-typescript)
//   src/api/constraints.gen.ts - each schema property's length, range and item-count
//                                limits and its default, which TypeScript types can't express
// `source` is a URL or a local JSON file; by default the running backend at API_URL
// (http://localhost:8000 unless set). Re-run after any backend/schemas.py change.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'

const LIMIT_KEYS = ['minLength', 'maxLength', 'minimum', 'maximum', 'minItems', 'maxItems']
const BANNER = "// Generated by `npm run gen:api` from the backend's OpenAPI schema. Do not edit by hand.\n\n"

async function load(arg) {
  if (arg && !/^https?:\/\//.test(arg)) return { schema: JSON.parse(readFileSync(arg, 'utf8')), from: arg }
  const url = arg ?? new URL('/openapi.json', process.env.API_URL ?? 'http://localhost:8000').href
  const response = await fetch(url)
  if (!response.ok) throw new Error(`${url} answered ${response.status}`)
  return { schema: await response.json(), from: url }
}

// A nullable field is anyOf [the real schema, null]; its limits sit on the first.
function limitsOf(property) {
  const found = {}
  for (const part of [property, ...(property.anyOf ?? [])]) {
    for (const key of LIMIT_KEYS) if (key in part) found[key] = part[key]
  }
  return found
}

function constraintsModule(schema) {
  const limits = {}
  const defaults = {}
  for (const [name, component] of Object.entries(schema.components.schemas)) {
    for (const [field, property] of Object.entries(component.properties ?? {})) {
      const found = limitsOf(property)
      if (Object.keys(found).length > 0) (limits[name] ??= {})[field] = found
      if ('default' in property) (defaults[name] ??= {})[field] = property.default
    }
  }
  const json = (value) => JSON.stringify(value, null, 2)
  return `${BANNER}export const limits = ${json(limits)} as const\n\nexport const defaults = ${json(defaults)} as const\n`
}

function write(relative, text) {
  const out = new URL(relative, import.meta.url)
  writeFileSync(out, text)
  return fileURLToPath(out)
}

const { schema, from } = await load(process.argv[2])
const types = write('../src/api/schema.gen.ts', BANNER + astToString(await openapiTS(schema)))
const constraints = write('../src/api/constraints.gen.ts', constraintsModule(schema))
process.stdout.write(`from ${from}\nwrote ${types}\nwrote ${constraints}\n`)
